-- 1) id 1/2/3 换成各自的专属概念海报
--
--    这三部片名要么未上映(流浪地球3 / 沙丘3), 要么完全是虚构(深海奇航),
--    原先借用了已上映影片的官方海报, 演示时容易被误认成张冠李戴。
--    改为本仓库自带的原创概念图(cinema-web/public/posters/):
--      /posters/wandering-earth-3.jpg  <- 流浪地球3
--      /posters/dune-3.jpg             <- 沙丘3
--      /posters/deep-sea-voyage.jpg    <- 深海奇航
--
--    /posters/xxx.jpg 是站点根绝对路径(Vite 会把 public/ 挂到根),
--    http://localhost:5173/posters/dune-3.jpg 可直接访问。
--    注意: 若把海报删了, 前端会显示裂图而不是占位图 —— 首页的 v-if 只判空值。
--
--    幂等: 重跑写入同值, 无副作用。
-- ============================================================
UPDATE movie SET poster = '/posters/wandering-earth-3.jpg' WHERE id = 1;
UPDATE movie SET poster = '/posters/dune-3.jpg'            WHERE id = 2;
UPDATE movie SET poster = '/posters/deep-sea-voyage.jpg'   WHERE id = 3;

