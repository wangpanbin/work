-- 执行: mysql -uroot -p --default-character-set=utf8mb4 < sql/07_real_demo_movies.sql
--   (必须带 --default-character-set=utf8mb4, 否则中文片名会被双重编码成乱码)
--
-- 用途:
--   1) 把 id 1/2/3 的"借用海报"换成各自的专属概念海报
--   2) 补 5 部真实上映的影片, 供课程演示
--
-- 为什么用 ON DUPLICATE KEY UPDATE 而不是 INSERT IGNORE:
--   04_extra_demo_data.sql 用的是 INSERT IGNORE, 重跑时若 ID 已存在就整行跳过 ——
--   字段写错后永远改不回来, 而且脚本照样返回成功(静默失败)。
--   07 改用 ON DUPLICATE KEY UPDATE, 重跑会刷新全部字段:
--   既是真幂等(同值重跑无副作用), 又能顺手修掉历史写错的 poster URL。
--
-- id 的取值约束(重要, 别随手改成雪花 ID):
--   sql/05_refresh_sessions_for_demo.sql 的游标是
--     SELECT id FROM movie WHERE status = 1 AND id < 1000;
--   只有 id < 1000 且 status = 1 的影片才会被自动排场次。
--   新片用 113-117(接在 101-112 之后), 既满足 < 1000, 又避开雪花 ID。
--   若误改成雪花 ID 或 >= 1000, 影片详情页会是空的"暂无场次"。
--
-- 执行顺序:
--   1) 本脚本
--   2) sql/05_refresh_sessions_for_demo.sql  (为新片补今天/明天/后天场次)
--   执行完 05 的预期场次规模: 20 部影片 x 3 天 x 4 时段 = 240
--
-- 不要在执行本脚本之后重跑 04_extra_demo_data.sql:
--   04 的场次 ID 用相对天数(d=1..14)编码, 已经跑过一次后重跑会撞上
--   历史 ID 被 INSERT IGNORE 静默跳过(详见 05 开头的说明)。
--
-- 数据来源(全部经核实, 不是凭印象填的):
--   片长 / 简介 / 海报: TMDB 影片页 div.facts > span.runtime, 以及
--                      /search/trending 的 JSON 原文
--   上映日期: TMDB 的 release_date 字段是"泛用上映日", 不等于中国内地上映日,
--             所以《长安的荔枝》改用腾讯新闻·深焦 + 百度百科双来源确认的
--             2025-07-18(中国大陆), 而不是 TMDB 字段里的 2025-07-12
--   5 张海报 URL 均已开图肉眼核对过, 与片名一一对应
-- ============================================================

